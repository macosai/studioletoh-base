return function(t)
  local color = require("letoh.base.color")

  t.test("normalize hex with hash", function()
    local c = color.normalize_rgb("#FF8000")
    t.eq(c.r, 255)
    t.eq(c.g, 128)
    t.eq(c.b, 0)
  end)

  t.test("normalize hex without hash", function()
    local c = color.normalize_rgb("ff8000")
    t.eq(c.r, 255)
    t.eq(c.g, 128)
    t.eq(c.b, 0)
  end)

  t.test("normalize table with named keys", function()
    local c = color.normalize_rgb({ r = 255, g = 128, b = 0 })
    t.eq(c.r, 255)
    t.eq(c.g, 128)
    t.eq(c.b, 0)
  end)

  t.test("normalize table with array keys", function()
    local c = color.normalize_rgb({ 1, 2, 3 })
    t.eq(c.r, 1)
    t.eq(c.g, 2)
    t.eq(c.b, 3)
  end)

  t.test("normalize floors fractional values", function()
    local c = color.normalize_rgb({ 1.9, 2.1, 3.7 })
    t.eq(c.r, 1)
    t.eq(c.g, 2)
    t.eq(c.b, 3)
  end)

  t.test("format_hex", function()
    t.eq(color.format_hex({ r = 255, g = 128, b = 0 }), "#FF8000")
  end)

  t.test("format_hex accepts a hex string", function()
    t.eq(color.format_hex("#ff8000"), "#FF8000")
  end)

  t.test("palette set and get", function()
    local p = color.palette.new()
    p:set("Lead", "#E2A13F")
    local c = p:get("Lead")
    t.eq(c.r, 226)
    t.eq(c.g, 161)
    t.eq(c.b, 63)
  end)

  t.test("palette get returns a copy", function()
    local p = color.palette.new({ slots = { Lead = "#E2A13F" } })
    local c = p:get("Lead")
    c.r = 0
    t.eq(p:get("Lead").r, 226)
  end)

  t.test("palette names are sorted", function()
    local p = color.palette.new({ slots = { Verse = "#000000", Chorus = "#FFFFFF" } })
    local names = p:names()
    t.eq(names[1], "Chorus")
    t.eq(names[2], "Verse")
  end)

  t.test("palette apply_to sorted targets", function()
    local p = color.palette.new({ slots = { A = "#000000", B = "#FFFFFF" } })
    local out = p:apply_to({ Verse = true, Chorus = true })
    t.eq(color.format_hex(out.Chorus), "#000000")
    t.eq(color.format_hex(out.Verse), "#FFFFFF")
  end)

  t.test("palette apply_to explicit order", function()
    local p = color.palette.new({ slots = { A = "#000000", B = "#FFFFFF" } })
    local out = p:apply_to({ Verse = true, Chorus = true }, { "Verse", "Chorus" })
    t.eq(color.format_hex(out.Verse), "#000000")
    t.eq(color.format_hex(out.Chorus), "#FFFFFF")
  end)

  t.test("rejects invalid hex", function()
    t.errors(function() color.normalize_rgb("#GGGGGG") end, "HEX", "invalid")
  end)

  t.test("rejects out-of-range RGB", function()
    t.errors(function() color.normalize_rgb({ 300, 0, 0 }) end, "RGB", "range")
  end)

  t.test("rejects unknown slot", function()
    local p = color.palette.new()
    t.errors(function() p:get("Missing") end, "unknown slot", "missing")
  end)

  t.test("rejects nil targets", function()
    local p = color.palette.new({ slots = { A = "#000000" } })
    t.errors(function() p:apply_to(nil) end, "targets", "nil")
  end)

  t.test("rejects order entry missing from targets", function()
    local p = color.palette.new({ slots = { A = "#000000" } })
    t.errors(function() p:apply_to({ Verse = true }, { "Chorus" }) end, "not found", "missing")
  end)

  t.test("rejects empty palette", function()
    local p = color.palette.new()
    t.errors(function() p:apply_to({ Verse = true }) end, "no slots", "empty")
  end)
end
